// Dynamic (wallpaper) color is intentionally NOT supported: a branded game owns its
// palette, and the previous dynamicColor=true default was why the chrome followed the
// wallpaper while the buttons stayed brand brown. System bars are handled solely by
// enableEdgeToEdge() in MainActivity (SystemBarStyle.auto follows uiMode).
@Composable
fun ChessTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val chessColors = if (darkTheme) DarkChessColors else LightChessColors

    CompositionLocalProvider(LocalChessColors provides chessColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}

// Accessor for the chess-domain tokens, mirroring how material3's MaterialTheme object
// sits beside its composable function: ChessTheme.colors.boardDark etc.
object ChessTheme {
    val colors: ChessColors
        @Composable @ReadOnlyComposable get() = LocalChessColors.current
}
